"""Canonical published image; the baked default for the generated shims."""

POSTGRES_IMAGE = "postgres:18.6-trixie"
"""Pinned image for the portal's database container.

The minor is bumped with each release; the Debian variant never changes,
because a base-OS switch changes collations under existing text indexes.
"""

POSTGRES_MAJOR = "18"
"""Major of :data:`POSTGRES_IMAGE`; selects the per-major ``PGDATA`` directory."""

_MCP_STUB_TEMPLATE = """\
#!/usr/bin/env sh
# WhyGraph whygraph-mcp stub. The stdio MCP server was removed in 2.0.0; agents
# now connect to the portal over HTTP. This stub stays for the 2.x line so a 1.x
# agent config that still runs `whygraph-mcp` gets a clear message. It never
# calls docker. Generated by `whygraph install`; safe to re-generate.
echo '__MESSAGE__' >&2
exit __EXIT__
"""

_PORTAL_VERBS = r"""
# --- portal verbs: up / down / status / logs / folders / backup ------------
# `whygraph up` runs the portal in ONE named, long-lived container, plus its
# Postgres in a second one ($PORTAL-postgres, no published port). Nothing from
# the host environment reaches either (keys live in the portal DB), so no `-e`
# here passes a credential variable. Config lives under ~/.config/whygraph, the
# portal's data under ~/.local/share/whygraph (mounted at /data).
portal_die() { echo "whygraph: $*" >&2; exit 2; }

portal_state() {
    docker inspect --type container -f '{{.State.Status}}' "$PORTAL" 2>/dev/null || true
}

portal_label() {
    docker inspect --type container -f '{{index .Config.Labels "'"$1"'"}}' "$PORTAL" 2>/dev/null || true
}

portal_pg_state() {
    docker inspect --type container -f '{{.State.Status}}' "$PG" 2>/dev/null || true
}

portal_pg_label() {
    docker inspect --type container -f '{{index .Config.Labels "whygraph.pg_image"}}' "$PG" 2>/dev/null || true
}

# Host-side checks and the password for the database container; starts nothing.
# PGDATA is per major ($DATA/postgres/<major>/docker), so a data dir another
# major created is refused rather than started on.
portal_pg_prepare() {
    { mkdir -p "$DATA/postgres" && chmod 700 "$DATA/postgres"; } || portal_die "cannot create $DATA/postgres"
    for v in "$DATA"/postgres/*/docker/PG_VERSION; do
        [ -f "$v" ] || continue
        [ "$(cat "$v")" != "$PG_MAJOR" ] || continue
        [ ! -f "$DATA/postgres/$PG_MAJOR/docker/PG_VERSION" ] || continue
        portal_die "the portal database in $DATA/postgres was created by Postgres $(cat "$v"); this release needs $PG_MAJOR. See https://mtrdesign.github.io/whygraph/portal/upgrading/#postgres-major"
    done
    if [ ! -s "$DATA/postgres.password" ]; then
        # The password only takes effect at initdb. A new one for an existing
        # cluster would lock the portal out, so refuse instead of regenerating.
        for v in "$DATA"/postgres/*/docker/PG_VERSION; do
            if [ -f "$v" ]; then
                portal_die "$DATA/postgres.password is missing but the database already exists - restore the file from your backup of this data dir"
            fi
        done
        { ( umask 077 && od -An -N24 -tx1 /dev/urandom | tr -d ' \n' > "$DATA/postgres.password.tmp" ) \
            && [ -s "$DATA/postgres.password.tmp" ] \
            && mv "$DATA/postgres.password.tmp" "$DATA/postgres.password"; } \
            || { rm -f "$DATA/postgres.password.tmp"; portal_die "cannot write the database password"; }
    fi
}

# pg_dump of the running database into $DATA/backups (0700), newest 10 kept.
# The dump goes to a .tmp first, so a failed one never leaves a truncated
# .dump for retention to count. $BACKUP_HINT is appended to every refusal.
portal_backup() {
    [ "$(portal_pg_state)" = "running" ] || portal_die "the portal database is not running - start it with: whygraph up$BACKUP_HINT"
    { mkdir -p "$DATA/backups" && chmod 700 "$DATA/backups"; } || portal_die "cannot create $DATA/backups$BACKUP_HINT"
    pg_dump_file="$DATA/backups/portal-$(date -u +%Y%m%dT%H%M%SZ).dump"
    if ! ( umask 077 && docker exec "$PG" pg_dump -U whygraph -d whygraph -Fc > "$pg_dump_file.tmp" ); then
        rm -f "$pg_dump_file.tmp"
        portal_die "the database backup failed (pg_dump in $PG)$BACKUP_HINT"
    fi
    mv "$pg_dump_file.tmp" "$pg_dump_file" || portal_die "cannot write $pg_dump_file$BACKUP_HINT"
    # Only the shim's own timestamped dumps count, and only those are deleted.
    ls -1 "$DATA/backups" | grep -x 'portal-[0-9]\{8\}T[0-9]\{6\}Z\.dump' | sort -r | tail -n +11 \
        | while IFS= read -r pg_old; do rm -f "$DATA/backups/$pg_old"; done
    echo "portal database backed up to $pg_dump_file"
    echo "restore needs this data dir's secret.key too - back it up with the dump"
}

portal_valid_port() {
    case "$1" in ''|*[!0-9]*) portal_die "invalid port '$1'" ;; esac
    if [ "$1" -lt 1 ] || [ "$1" -gt 65535 ]; then portal_die "invalid port '$1'"; fi
}

# Precedence: the persisted port (`up --port N` writes it), then the exported
# WHYGRAPH_PORT, then 8765.
portal_resolve_port() {
    PORT=""
    if [ -f "$CONF/port" ]; then read -r PORT < "$CONF/port" || true; fi
    [ -n "$PORT" ] || PORT="${WHYGRAPH_PORT:-8765}"
    portal_valid_port "$PORT"
}

# The data dir must exist, owned by the host user, before `docker run`: a
# missing bind source is otherwise created root-owned on a Linux engine.
portal_prepare() {
    mkdir -p "$DATA" "$HOME/.config/whygraph" && chmod 700 "$DATA"
    DATA=$(cd -- "$DATA" && pwd -P)
    case "$DATA" in *,*|*\"*) portal_die "data directory '$DATA' must not contain ',' or a double quote" ;; esac
    touch "$FOLDERS_FILE"
}

# True when $1 is the data dir, inside it, or contains it.
portal_overlaps_data() {
    case "$1/" in "$DATA"/*) return 0 ;; esac
    case "$DATA/" in "$1"/*) return 0 ;; esac
    return 1
}

# Validate and canonicalise a shared folder into $NORM (exits 2 on refusal).
# ':' would break WHYGRAPH_SHARED_FOLDERS, ',' and '"' would break --mount.
portal_norm_folder() {
    case "$1" in
        *:*|*,*|*\"*|*"$NL"*)
            portal_die "shared folder '$1': ':' ',' double quotes and newlines are not allowed in the path" ;;
    esac
    [ -d "$1" ] || portal_die "shared folder '$1' is not a directory"
    NORM=$(cd -- "$1" && pwd -P) || portal_die "cannot resolve shared folder '$1'"
    case "$NORM" in
        *:*|*,*|*\"*|*"$NL"*)
            portal_die "shared folder '$NORM': ':' ',' double quotes and newlines are not allowed in the path" ;;
    esac
    [ "$NORM" != "/" ] || portal_die "refusing to share '/'"
    if portal_overlaps_data "$NORM"; then
        portal_die "shared folder '$NORM' overlaps the data directory '$DATA'"
    fi
}

# Development only (`make dev-docker`): WHYGRAPH_DEV_SRC names a WhyGraph
# checkout to run instead of the installed package. Canonicalise it into
# $DEV_SRC, refusing what would break --mount (exits 2).
portal_dev_src() {
    case "$1" in
        /*) ;;
        *) portal_die "WHYGRAPH_DEV_SRC '$1' must be an absolute path" ;;
    esac
    [ -f "$1/src/whygraph/__init__.py" ] && [ -f "$1/scripts/dev_portal.py" ] \
        || portal_die "WHYGRAPH_DEV_SRC '$1' is not a WhyGraph checkout"
    DEV_SRC=$(cd -- "$1" && pwd -P) || portal_die "cannot resolve WHYGRAPH_DEV_SRC '$1'"
    case "$DEV_SRC" in
        *:*|*,*|*\"*|*"$NL"*)
            portal_die "WHYGRAPH_DEV_SRC '$DEV_SRC': ':' ',' double quotes and newlines are not allowed in the path" ;;
    esac
}

# Validate one --add-folder argument and queue it (deduped) for the folders file.
portal_queue_folder() {
    portal_norm_folder "$1"
    if [ "$NORM" = "$(cd -- "$HOME" && pwd -P)" ]; then
        echo "warning: sharing your home directory exposes every project under it; prefer a narrower folder" >&2
    fi
    if grep -Fxq -e "$NORM" "$FOLDERS_FILE"; then return 0; fi
    case "$NL$pending$NL" in *"$NL$NORM$NL"*) return 0 ;; esac
    pending="${pending:+$pending$NL}$NORM"
}

# Once only (sentinel): names of credential variables set on the host, never values.
portal_env_hint() {
    [ ! -e "$CONF/env-hint-shown" ] || return 0
    names=""
    for v in GH_TOKEN GITHUB_TOKEN ANTHROPIC_API_KEY OPENAI_API_KEY DEEPSEEK_API_KEY OPENROUTER_API_KEY; do
        eval "val=\${$v:-}"
        if [ -n "$val" ]; then names="${names:+$names, }$v"; fi
    done
    [ -n "$names" ] || return 0
    case "$names" in *,*) verb="are"; reach="do" ;; *) verb="is"; reach="does" ;; esac
    echo "note: $names $verb set in your shell but $reach not reach the portal. Enter keys and tokens under Settings in the portal." >&2
    : > "$CONF/env-hint-shown"
}

portal_up() {
    new_port=""
    port_given=""
    pending=""
    while [ $# -gt 0 ]; do
        case "$1" in
            --port) [ $# -ge 2 ] || portal_die "--port needs a value"; new_port="$2"; port_given=1; shift 2 ;;
            --port=*) new_port="${1#--port=}"; port_given=1; shift ;;
            --add-folder) [ $# -ge 2 ] || portal_die "--add-folder needs a directory"; portal_queue_folder "$2"; shift 2 ;;
            --add-folder=*) portal_queue_folder "${1#--add-folder=}"; shift ;;
            -h|--help) echo "usage: whygraph up [--port N] [--add-folder DIR]..."; exit 0 ;;
            *) portal_die "whygraph up: unknown arg '$1'" ;;
        esac
    done
    [ -z "$port_given" ] || portal_valid_port "$new_port"
    [ -z "$pending" ] || printf '%s\n' "$pending" >> "$FOLDERS_FILE"
    [ -z "$port_given" ] || printf '%s\n' "$new_port" > "$CONF/port"
    portal_resolve_port

    # Same-path bind mounts, built with `set --` so paths with spaces survive.
    # `--mount` (unlike `-v`) errors on a missing source instead of creating it.
    set -- --mount "type=bind,source=$DATA,target=/data"
    FOLDERS_JOINED=""
    while IFS= read -r f || [ -n "$f" ]; do
        [ -n "$f" ] || continue
        [ -d "$f" ] || portal_die "shared folder '$f' no longer exists (remove it: whygraph folders --remove '$f')"
        if portal_overlaps_data "$f"; then portal_die "shared folder '$f' overlaps the data directory '$DATA'"; fi
        set -- "$@" --mount "type=bind,source=$f,target=$f"
        FOLDERS_JOINED="${FOLDERS_JOINED:+$FOLDERS_JOINED:}$f"
    done < "$FOLDERS_FILE"

    # The container's hostname. Without it the portal reports the container id
    # as this machine's name when a project is linked to a platform. Recorded
    # as a label, so a renamed machine recreates the container like a port or
    # folder change does. Anything docker would refuse as a hostname (or no
    # `hostname` at all) leaves it to docker.
    HOST_NAME=$(hostname -s 2>/dev/null || hostname 2>/dev/null || true)
    HOST_NAME=$(printf '%.63s' "$HOST_NAME")
    case "$HOST_NAME" in ''|-*|*-|*[!A-Za-z0-9.-]*) HOST_NAME="" ;; esac
    [ -z "$HOST_NAME" ] || set -- "$@" --hostname "$HOST_NAME"

    # Dev mode: the checkout read-only over the installed package, a Linux
    # node_modules for Vite, the Vite port, and the dev wrapper as the command.
    DEV_SRC=""
    RESTART="unless-stopped"
    if [ -n "${WHYGRAPH_DEV_SRC:-}" ]; then
        portal_dev_src "$WHYGRAPH_DEV_SRC"
        RESTART="no"
        mkdir -p "$DATA/dev-node_modules" "$DEV_SRC/src/playground/node_modules"
        set -- "$@" --mount "type=bind,source=$DEV_SRC,target=/opt/whygraph-dev,readonly" \
            --mount "type=bind,source=$DATA/dev-node_modules,target=/opt/whygraph-dev/src/playground/node_modules" \
            --label "whygraph.dev_src=$DEV_SRC" \
            -p "127.0.0.1:5174:5174" \
            -e PYTHONPATH=/opt/whygraph-dev/src \
            -e "WHYGRAPH_SCAN_CMD=env PYTHONPATH=/opt/whygraph-dev/src python -m whygraph scan" \
            -e WHYGRAPH_DEV_ORIGINS=http://localhost:5174,http://127.0.0.1:5174
        set -- "$@" "$IMAGE" python /opt/whygraph-dev/scripts/dev_portal.py --vite-host 0.0.0.0 --
    else
        set -- "$@" "$IMAGE" whygraph portal
    fi

    URL="http://127.0.0.1:$PORT"
    if docker inspect --type container -f '{{.State.Status}}' whygraph-serve >/dev/null 2>&1; then
        echo "warning: a 'whygraph-serve' container from the old playground still exists (it may hold port 8765). Remove it with: whygraph serve --stop" >&2
    fi

    # Decide everything first, then act: the portal always stops before its
    # database, so a running scan can still record itself as interrupted.
    portal_pg_prepare
    pg_state=$(portal_pg_state)
    pg_changed=""
    case "$pg_state" in
        running|restarting) [ "$(portal_pg_label)" = "$PG_IMAGE" ] || pg_changed=1 ;;
        *) pg_changed=1 ;;
    esac
    # Dump a running database before it is recreated - before either container
    # is touched, so a failed dump leaves both exactly as they were.
    if [ -n "$pg_changed" ] && [ "$pg_state" = "running" ]; then
        if [ "${WHYGRAPH_SKIP_BACKUP:-}" = "1" ]; then
            echo "whygraph: WHYGRAPH_SKIP_BACKUP=1 - recreating the portal database without a backup" >&2
        else
            echo "whygraph portal: backing up the database before recreating it" >&2
            BACKUP_HINT=" - nothing was changed; to recreate it without a backup: WHYGRAPH_SKIP_BACKUP=1 whygraph up"
            portal_backup
            BACKUP_HINT=""
        fi
    fi

    state=$(portal_state)
    if [ -n "$state" ]; then
        case "$state" in
            running|restarting)
                changed=""
                [ "$(portal_label whygraph.folders)" = "$FOLDERS_JOINED" ] || changed="$changed folders"
                [ "$(portal_label whygraph.port)" = "$PORT" ] || changed="$changed port"
                [ "$(portal_label whygraph.image)" = "$IMAGE" ] || changed="$changed image"
                [ "$(portal_label whygraph.hostname)" = "$HOST_NAME" ] || changed="$changed hostname"
                [ "$(portal_label whygraph.dev_src)" = "$DEV_SRC" ] || changed="$changed dev_src"
                [ -z "$pg_changed" ] || changed="$changed database"
                if [ -z "$changed" ]; then
                    if [ "$state" = "restarting" ]; then
                        echo "whygraph portal is restarting (see: whygraph logs)" >&2
                    else
                        echo "whygraph portal already running at $URL"
                    fi
                    portal_env_hint
                    return 0
                fi
                echo "whygraph portal: recreating (changed:$changed)" >&2
                docker stop -t "$GRACE" "$PORTAL" >/dev/null
                docker rm "$PORTAL" >/dev/null ;;
            *) docker rm -f "$PORTAL" >/dev/null ;;
        esac
    fi

    # The network must exist before the database joins it.
    docker network create whygraph-portal >/dev/null 2>&1 || true
    if [ -n "$pg_changed" ]; then
        [ "$pg_state" != "running" ] || docker stop -t "$GRACE" "$PG" >/dev/null
        [ -z "$pg_state" ] || docker rm -f "$PG" >/dev/null
        # No -p: the database is reachable only on the whygraph-portal network.
        # The health check uses TCP on purpose: the image's first-run temporary
        # server listens on the socket only, so it cannot pass early.
        docker run -d --name "$PG" --restart "$RESTART" --network whygraph-portal \
            --label "whygraph.pg_image=$PG_IMAGE" \
            --user "$(id -u):$(id -g)" \
            --shm-size=128m \
            --health-cmd "pg_isready -h 127.0.0.1 -U whygraph -d whygraph" \
            --health-interval 2s --health-timeout 3s --health-retries 30 --health-start-period 5s \
            --mount "type=bind,source=$DATA/postgres,target=/var/lib/postgresql" \
            --mount "type=bind,source=$DATA/postgres.password,target=/run/secrets/whygraph-db-password,readonly" \
            -e "PGDATA=/var/lib/postgresql/$PG_MAJOR/docker" \
            -e POSTGRES_USER=whygraph -e POSTGRES_DB=whygraph \
            -e POSTGRES_PASSWORD_FILE=/run/secrets/whygraph-db-password \
            "$PG_IMAGE" >/dev/null
    fi
    # Always wait (60 s): this also covers a database Docker has just restarted.
    # WHYGRAPH_DB_READY_TIMEOUT only exists to keep the test suite fast.
    pg_budget="${WHYGRAPH_DB_READY_TIMEOUT:-60}"
    case "$pg_budget" in ''|*[!0-9]*) pg_budget=60 ;; esac
    pg_waited=0
    while :; do
        pg_health=$(docker inspect --type container -f '{{.State.Health.Status}}' "$PG" 2>/dev/null || true)
        [ "$pg_health" != "healthy" ] || break
        if [ "$pg_health" = "unhealthy" ] || [ "$pg_waited" -ge "$pg_budget" ]; then
            portal_die "the portal database did not become ready - see: docker logs $PG"
        fi
        sleep 1
        pg_waited=$((pg_waited + 1))
    done

    docker run -d --init --name "$PORTAL" --restart "$RESTART" \
        --network whygraph-portal --add-host=host.docker.internal:host-gateway \
        --label "whygraph.folders=$FOLDERS_JOINED" --label "whygraph.port=$PORT" \
        --label "whygraph.image=$IMAGE" --label "whygraph.hostname=$HOST_NAME" \
        -p "127.0.0.1:$PORT:$PORT" \
        --user "$(id -u):$(id -g)" -e HOME=/tmp \
        -e WHYGRAPH_DATA=/data -e WHYGRAPH_SHARED_FOLDERS="$FOLDERS_JOINED" \
        -e WHYGRAPH_MODE=local -e WHYGRAPH_PORT="$PORT" \
        -e "WHYGRAPH_DATABASE_URL=postgresql+psycopg://whygraph@$PG:5432/whygraph" \
        -e WHYGRAPH_DATABASE_PASSWORD_FILE=/data/postgres.password \
        "$@" --host 0.0.0.0 --port "$PORT" >/dev/null
    echo "whygraph portal running at $URL"
    portal_env_hint
}

# Each container on its own, portal first; the data stays in $DATA/postgres.
portal_down() {
    [ $# -eq 0 ] || portal_die "whygraph down takes no arguments"
    pg_stopped=""
    if [ -n "$(portal_state)" ]; then
        docker stop -t "$GRACE" "$PORTAL" >/dev/null
        docker rm "$PORTAL" >/dev/null
        echo "whygraph portal stopped"
        pg_stopped=1
    fi
    if [ -n "$(portal_pg_state)" ]; then
        docker stop -t "$GRACE" "$PG" >/dev/null
        docker rm "$PG" >/dev/null
        echo "whygraph portal database stopped (its data stays in $DATA/postgres)"
        pg_stopped=1
    fi
    [ -n "$pg_stopped" ] || echo "whygraph portal is not running" >&2
}

portal_status() {
    [ $# -eq 0 ] || portal_die "whygraph status takes no arguments"
    state=$(portal_state)
    pg_state=$(portal_pg_state)
    if [ -n "$pg_state" ]; then pg_line="database: $pg_state ($(portal_pg_label))"; else pg_line="database: not created"; fi
    if [ -z "$state" ]; then
        echo "whygraph portal: not created (start it with: whygraph up)"
        echo "$pg_line"
        return 1
    fi
    echo "whygraph portal: $state"
    echo "url: http://127.0.0.1:$(portal_label whygraph.port)"
    echo "image: $(portal_label whygraph.image)"
    echo "$pg_line"
    folders=$(portal_label whygraph.folders)
    if [ -z "$folders" ]; then
        echo "folders: (none)"
    else
        echo "folders:"
        rest="$folders"
        while [ -n "$rest" ]; do
            case "$rest" in
                *:*) item="${rest%%:*}"; rest="${rest#*:}" ;;
                *) item="$rest"; rest="" ;;
            esac
            echo "  $item"
        done
    fi
    [ "$state" = "running" ] && [ "$pg_state" = "running" ]
}

portal_logs() {
    [ $# -eq 0 ] || portal_die "whygraph logs takes no arguments"
    exec docker logs -f "$PORTAL"
}

portal_folders() {
    remove=""
    while [ $# -gt 0 ]; do
        case "$1" in
            --remove) [ $# -ge 2 ] || portal_die "--remove needs a directory"; remove="$2"; shift 2 ;;
            --remove=*) remove="${1#--remove=}"; shift ;;
            *) portal_die "whygraph folders: unknown arg '$1'" ;;
        esac
    done
    if [ -z "$remove" ]; then
        if [ -s "$FOLDERS_FILE" ]; then cat "$FOLDERS_FILE"; else echo "no shared folders (add one: whygraph up --add-folder DIR)" >&2; fi
        return 0
    fi
    target="$remove"
    if [ -d "$remove" ]; then target=$(cd -- "$remove" && pwd -P); fi
    found=""
    : > "$FOLDERS_FILE.tmp"
    while IFS= read -r f || [ -n "$f" ]; do
        [ -n "$f" ] || continue
        if [ "$f" = "$target" ]; then found=1; else printf '%s\n' "$f" >> "$FOLDERS_FILE.tmp"; fi
    done < "$FOLDERS_FILE"
    if [ -z "$found" ]; then
        rm -f "$FOLDERS_FILE.tmp"
        echo "whygraph: '$target' is not a shared folder (see: whygraph folders)" >&2
        return 1
    fi
    mv "$FOLDERS_FILE.tmp" "$FOLDERS_FILE"
    echo "removed shared folder $target"
    # A running portal keeps its old mounts until it is recreated.
    case "$(portal_state)" in
        running|restarting) portal_prepare; portal_up ;;
    esac
}

portal_main() {
    verb="$1"; shift
    # WHYGRAPH_PORTAL_NAME is for development (`make dev-docker` / `prod` and
    # the smoke test), so they never touch the user's own portal.
    PORTAL="${WHYGRAPH_PORTAL_NAME:-whygraph-portal}"
    case "$PORTAL" in
        [A-Za-z0-9]*) case "$PORTAL" in *[!A-Za-z0-9_.-]*) portal_die "invalid WHYGRAPH_PORTAL_NAME '$PORTAL'" ;; esac ;;
        *) portal_die "invalid WHYGRAPH_PORTAL_NAME '$PORTAL'" ;;
    esac
    PG="$PORTAL-postgres"
    PG_IMAGE="${WHYGRAPH_POSTGRES_IMAGE:-__PG_IMAGE__}"
    PG_MAJOR=__PG_MAJOR__
    BACKUP_HINT=""
    CONF="$HOME/.config/whygraph"
    FOLDERS_FILE="$CONF/folders"
    DATA="${WHYGRAPH_DATA:-$HOME/.local/share/whygraph}"
    GRACE="${WHYGRAPH_STOP_GRACE:-30}"
    NL="$(printf '\n_')"; NL="${NL%_}"
    case "$verb" in
        up) portal_prepare; portal_up "$@" ;;
        down) portal_down "$@" ;;
        status) portal_status "$@" ;;
        logs) portal_logs "$@" ;;
        folders) mkdir -p "$CONF"; touch "$FOLDERS_FILE"; portal_folders "$@" ;;
        backup) [ $# -eq 0 ] || portal_die "whygraph backup takes no arguments"; portal_backup ;;
    esac
}

case "${1:-}" in
    up|down|status|logs|folders|backup) portal_main "$@"; exit 0 ;;
esac
# --- end portal verbs ------------------------------------------------------
"""

# The `whygraph` shim carries the portal verbs on top of the ephemeral path, and
# a `serve` branch that only prints the 2.0 removal message (exit 2). Its
# `--stop` still removes a leftover 1.x `whygraph-serve` container, so upgraders
# are not left with one holding the port.
_WHYGRAPH_SHIM_TEMPLATE = """\
#!/usr/bin/env sh
# WhyGraph shim. Every command runs ephemerally in the container EXCEPT
# `whygraph up|down|status|logs|folders|backup`, which manage the long-lived
# portal container and its database container (and `whygraph serve`, removed
# in 2.0.0, which only says so).
# Generated by `whygraph install`; safe to re-generate.
set -eu
IMAGE="${WHYGRAPH_IMAGE:-__IMAGE__}"
__PORTAL_VERBS__
if [ "${1:-}" = "serve" ]; then
    if [ "${2:-}" = "--stop" ]; then
        exec docker rm -f whygraph-serve
    fi
    echo '__SERVE_REMOVED__' >&2
    exit __EXIT__
fi

# Every other command — unchanged ephemeral path, no port, no name.
tty=""
[ -t 0 ] && [ -t 1 ] && tty="-t"
exec docker run --rm -i $tty \\
    --user "$(id -u):$(id -g)" -e HOME=/tmp \\
    -v "$PWD:/workspace" -w /workspace \\
    -e GH_TOKEN -e GITHUB_TOKEN \\
    -e ANTHROPIC_API_KEY -e OPENAI_API_KEY -e DEEPSEEK_API_KEY \\
    -e OPENROUTER_API_KEY \\
    "$IMAGE" whygraph "$@"
"""

_INSTALLER_TEMPLATE = """\
#!/usr/bin/env sh
# WhyGraph installer — emitted by `whygraph install` from inside the image.
# Writes the `whygraph` shim onto your PATH (it runs this image against the
# current directory, and the portal via `whygraph up`), plus a `whygraph-mcp`
# stub that says the stdio server was removed. Re-run any time to refresh.
set -eu

BIN_DIR="${WHYGRAPH_BIN_DIR:-$HOME/.local/bin}"
mkdir -p "$BIN_DIR"

cat > "$BIN_DIR/whygraph" <<'WHYGRAPH_SHIM'
__WHYGRAPH_SHIM__
WHYGRAPH_SHIM
chmod +x "$BIN_DIR/whygraph"
echo "installed $BIN_DIR/whygraph"

cat > "$BIN_DIR/whygraph-mcp" <<'WHYGRAPH_MCP_STUB'
__WHYGRAPH_MCP_STUB__
WHYGRAPH_MCP_STUB
chmod +x "$BIN_DIR/whygraph-mcp"
echo "installed $BIN_DIR/whygraph-mcp"

case ":$PATH:" in
    *":$BIN_DIR:"*) ;;
    *) echo "note: add $BIN_DIR to your PATH, e.g. 'export PATH=\\"$BIN_DIR:\\$PATH\\"'" ;;
esac

echo "done. Try:  whygraph up"
"""


def _shim(image: str) -> str:
    """Render the ``whygraph`` shim's body, baking ``image`` as its default.

    Renders :data:`_WHYGRAPH_SHIM_TEMPLATE` with the portal verbs from
    :data:`_PORTAL_VERBS` (baking :data:`POSTGRES_IMAGE` / :data:`POSTGRES_MAJOR`
    for the database container) and the ``serve`` removal branch.
    """
    return (
        _WHYGRAPH_SHIM_TEMPLATE.replace("__PORTAL_VERBS__", _PORTAL_VERBS)
        .replace("__PG_IMAGE__", POSTGRES_IMAGE)
        .replace("__PG_MAJOR__", POSTGRES_MAJOR)
        .replace("__SERVE_REMOVED__", _sh_single_quoted(SERVE_REMOVED))
        .replace("__EXIT__", str(REMOVED_EXIT_CODE))
        .replace("__IMAGE__", image)
    )


def _mcp_stub() -> str:
    """Render the host ``whygraph-mcp`` stub (no image, no ``docker``)."""
    return _MCP_STUB_TEMPLATE.replace(
        "__MESSAGE__", _sh_single_quoted(MCP_REMOVED)
    ).replace("__EXIT__", str(REMOVED_EXIT_CODE))


def _sh_single_quoted(text: str) -> str:
    """Return ``text`` for use inside ``'...'`` (it must hold no single quote)."""
    if "'" in text:
        raise ValueError(f"message contains a single quote: {text!r}")
    return text


def render_installer(image: str) -> str:
    """Render the full installer: the ``whygraph`` shim and the ``whygraph-mcp`` stub.

    Parameters
    ----------
    image : str
        The image reference baked as the shim's ``WHYGRAPH_IMAGE`` default,
        e.g. ``ghcr.io/mtrdesign/whygraph:1.2.3``.

    Returns
    -------
    str
        A self-contained POSIX ``sh`` script, newline-terminated.
    """
    return _INSTALLER_TEMPLATE.replace(
        "__WHYGRAPH_MCP_STUB__", _mcp_stub().rstrip("\n")
    ).replace("__WHYGRAPH_SHIM__", _shim(image).rstrip("\n"))


@click.command(name="install")
def install_cmd() -> None:
    """Emit the host shim installer (called by ``scripts/install.sh``).

    Prints a POSIX ``sh`` script that installs the ``whygraph`` shim (and
    the ``whygraph-mcp`` removal stub) onto ``PATH``. The shim is pinned to
    ``ghcr.io/mtrdesign/whygraph`` at this image's baked ``WHYGRAPH_VERSION``
    (``latest`` for un-versioned local builds), overridable per command via the
    ``WHYGRAPH_IMAGE`` environment variable.
    """
    version = os.environ.get("WHYGRAPH_VERSION", "latest")
    image = f"{IMAGE_REPO}:{version}"
    click.echo(render_installer(image), nl=False)


