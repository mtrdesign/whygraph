"""The ``whygraph install`` subcommand — emit the host shim installer.

WhyGraph ships as a single Docker image. This command prints a POSIX ``sh``
installer to **stdout**; running it writes the ``whygraph`` shim onto ``PATH``.
The shim runs the image ephemerally against the current directory (``docker run
--rm -v "$PWD:/workspace" …``), so every command is a fresh process reading that
repo's own ``whygraph.toml`` / ``.whygraph`` / ``.codegraph`` - except the portal
verbs (``up`` / ``down`` / ``status`` / ``logs`` / ``folders`` / ``backup``), which
manage the long-lived portal container and its database container. It also
writes a host ``whygraph-mcp`` **stub** in place of the 1.x shim: the stdio MCP server was removed in 2.0.0, and every 1.x
agent config still runs ``whygraph-mcp``, so the stub prints the removal message
to stderr and exits ``2`` without calling ``docker``. It stays for the 2.x line.

This is **in-image plumbing, not the user-facing install step**. The front door
is the host-side bootstrapper ``scripts/install.sh``, fetched from a tag-pinned
raw URL::

    curl -fsSL https://raw.githubusercontent.com/mtrdesign/whygraph/v2.0.0/scripts/install.sh | sh

That script probes Docker, pulls the pinned image, and then delegates here —
``docker run --rm IMAGE whygraph install`` — checking the output is non-empty
before executing it. Keeping generation in Python (rather than in the fetched
shell) means the shim bodies stay covered by ``tests/test_install_cmd.py`` and
cannot drift from the bootstrapper. Running that delegation by hand
(``docker run --rm IMAGE whygraph install | sh``) remains supported for
no-curl / air-gapped hosts, and printing it without the pipe is the way to
inspect exactly what would be written.

The image reference baked into the shim is ``ghcr.io/mtrdesign/whygraph`` at
the version baked into the image at build time (``WHYGRAPH_VERSION`` env, set by
the publish workflow), so an install freezes to a **concrete release** even when
pulled via ``:latest``. The shim still honours a ``WHYGRAPH_IMAGE`` override at
run time for mirrors / local builds.

Notes
-----
Only the installer script is written to stdout (via :func:`click.echo`); all
logging goes to stderr. That keeps the ``… | sh`` pipe clean — the container's
stderr surfaces on the terminal but never corrupts the piped script.
"""

from __future__ import annotations

import os

import click

from ..stubs import MCP_REMOVED, REMOVED_EXIT_CODE, SERVE_REMOVED

